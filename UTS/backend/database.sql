-- =====================================================
-- 1. TABEL BARANG
-- =====================================================

CREATE TABLE IF NOT EXISTS barang (

    id_barang BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_barang VARCHAR(20)
        NOT NULL
        UNIQUE,

    nama_barang VARCHAR(100)
        NOT NULL,

    kategori VARCHAR(50)
        NOT NULL,

    satuan VARCHAR(20)
        NOT NULL,

    harga_beli NUMERIC(15,2)
        NOT NULL
        DEFAULT 0,

    harga_jual NUMERIC(15,2)
        NOT NULL
        DEFAULT 0,

    stok INTEGER
        NOT NULL
        DEFAULT 0,

    stok_minimum INTEGER
        NOT NULL
        DEFAULT 0,

    CONSTRAINT cek_harga_beli
        CHECK (harga_beli >= 0),

    CONSTRAINT cek_harga_jual
        CHECK (harga_jual >= 0),

    CONSTRAINT cek_stok
        CHECK (stok >= 0),

    CONSTRAINT cek_stok_minimum
        CHECK (stok_minimum >= 0)
);


-- =====================================================
-- 2. TABEL PEMASOK
-- =====================================================

CREATE TABLE IF NOT EXISTS pemasok (

    id_pemasok BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_pemasok VARCHAR(20)
        NOT NULL
        UNIQUE,

    nama_pemasok VARCHAR(100)
        NOT NULL,

    alamat TEXT,

    no_telepon VARCHAR(20)
);


-- =====================================================
-- 3. TABEL PELANGGAN
-- =====================================================

CREATE TABLE IF NOT EXISTS pelanggan (

    id_pelanggan BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_pelanggan VARCHAR(20)
        NOT NULL
        UNIQUE,

    nama_pelanggan VARCHAR(100)
        NOT NULL,

    alamat TEXT,

    no_telepon VARCHAR(20)
);


-- =====================================================
-- 4. TABEL PEMBELIAN
-- =====================================================

CREATE TABLE IF NOT EXISTS pembelian (

    id_pembelian BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nomor_pembelian VARCHAR(30)
        NOT NULL
        UNIQUE,

    tanggal_pembelian DATE
        NOT NULL,

    id_pemasok BIGINT
        NOT NULL,

    total_pembelian NUMERIC(15,2)
        NOT NULL
        DEFAULT 0,

    CONSTRAINT fk_pembelian_pemasok
        FOREIGN KEY (id_pemasok)
        REFERENCES pemasok(id_pemasok),

    CONSTRAINT cek_total_pembelian
        CHECK (total_pembelian >= 0)
);


-- =====================================================
-- 5. DETAIL PEMBELIAN
-- =====================================================

CREATE TABLE IF NOT EXISTS detail_pembelian (

    id_detail_pembelian BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pembelian BIGINT
        NOT NULL,

    id_barang BIGINT
        NOT NULL,

    jumlah INTEGER
        NOT NULL,

    harga_beli NUMERIC(15,2)
        NOT NULL,

    subtotal NUMERIC(15,2)
        NOT NULL,

    CONSTRAINT fk_detail_pembelian
        FOREIGN KEY (id_pembelian)
        REFERENCES pembelian(id_pembelian)
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_barang_pembelian
        FOREIGN KEY (id_barang)
        REFERENCES barang(id_barang),

    CONSTRAINT cek_jumlah_pembelian
        CHECK (jumlah > 0),

    CONSTRAINT cek_harga_beli_detail
        CHECK (harga_beli >= 0),

    CONSTRAINT cek_subtotal_pembelian
        CHECK (subtotal >= 0)
);


