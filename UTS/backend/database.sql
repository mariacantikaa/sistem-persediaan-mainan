-- =====================================================
-- 8. TABEL AKUN
-- =====================================================

CREATE TABLE IF NOT EXISTS public.akun (

    id_akun BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_akun VARCHAR(20)
        NOT NULL
        UNIQUE,

    nama_akun VARCHAR(100)
        NOT NULL,

    jenis_akun VARCHAR(30)
        NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE
        DEFAULT NOW(),

    CONSTRAINT cek_jenis_akun
        CHECK (
            jenis_akun IN (
                'ASET',
                'KEWAJIBAN',
                'EKUITAS',
                'PENDAPATAN',
                'BEBAN'
            )
        )
);


