-- =====================================================
-- 10. TABEL JURNAL UMUM
-- =====================================================

CREATE TABLE IF NOT EXISTS public.jurnal_umum (

    id_jurnal BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    tanggal_jurnal DATE
        NOT NULL,

    nomor_bukti VARCHAR(30)
        NOT NULL,

    sumber_transaksi VARCHAR(30)
        NOT NULL,

    id_akun BIGINT
        NOT NULL,

    keterangan TEXT
        NOT NULL,

    debit NUMERIC(15,2)
        NOT NULL
        DEFAULT 0,

    kredit NUMERIC(15,2)
        NOT NULL
        DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE
        DEFAULT NOW(),

    CONSTRAINT fk_jurnal_akun
        FOREIGN KEY (id_akun)
        REFERENCES public.akun(id_akun),

    CONSTRAINT cek_debit_kredit
        CHECK (
            debit >= 0
            AND kredit >= 0
        ),

    CONSTRAINT cek_satu_sisi
        CHECK (
            NOT (
                debit > 0
                AND kredit > 0
            )
        )
);


-- =====================================================
-- 11. INDEX JURNAL
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_jurnal_tanggal
ON public.jurnal_umum(tanggal_jurnal);

CREATE INDEX IF NOT EXISTS idx_jurnal_nomor_bukti
ON public.jurnal_umum(nomor_bukti);

CREATE INDEX IF NOT EXISTS idx_jurnal_akun
ON public.jurnal_umum(id_akun);


